DEFAULT_FA_STRINGS = STRINGS["en"]


class I18nService:
    def __init__(self):
        self._cache: Dict[str, Dict[str, str]] = {k: v.copy() for k, v in STRINGS.items()}

    async def load_from_db(self, db: AsyncSession):
        """Loads custom translations from database into memory."""
        query = select(Translation)
        result = await db.execute(query)
        rows = result.scalars().all()
        for r in rows:
            if r.lang_code not in self._cache:
                self._cache[r.lang_code] = {}
            self._cache[r.lang_code][r.trans_key] = r.trans_value

    def get(self, key: str, lang: str = "en", default: Optional[str] = None, **kwargs) -> str:
        """Retrieves localized text with fallback to English then Persian."""
        target_lang = lang if lang in self._cache else DEFAULT_LANGUAGE
        lang_dict = self._cache.get(target_lang, {})
        
        text = (
            lang_dict.get(key)
            or self._cache.get("en", {}).get(key)
            or self._cache.get("fa", {}).get(key)
            or default
            or key
        )
        if kwargs:
            try:
                return text.format(**kwargs)
            except Exception:
                return text
        return text

    def get_all_button_texts(self, key: str) -> List[str]:
        """Returns button text across all supported languages for matching in handlers."""
        res = []
        for l in SUPPORTED_LANGUAGES.keys():
            t = self.get(key, lang=l)
            if t and t not in res:
                res.append(t)
        return res

    def get_status_label(self, status: str, lang: str = "en") -> str:
        return self.get(f"status_{status}", lang=lang, default=status)

    def get_field_type_label(self, ftype: str, lang: str = "en") -> str:
        return self.get(f"field_{ftype}", lang=lang, default=ftype)

    def get_tx_type_label(self, txtype: str, lang: str = "en") -> str:
        return self.get(f"tx_{txtype}", lang=lang, default=txtype)


i18n = I18nService()
